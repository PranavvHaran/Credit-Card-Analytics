CREATE OR REPLACE TABLE DIM_DATE (

    DATE_KEY INT,
    FULL_DATE DATE,
    YEAR INT,
    MONTH INT,
    MONTH_NAME VARCHAR(30),
    DAY INT,
    DAY_NAME VARCHAR(30),
    QUARTER VARCHAR(30),
    WEEKEND_FLAG VARCHAR(10)
);

DESCRIBE TABLE DIM_DATE;

INSERT INTO DIM_DATE
    SELECT 

     TO_NUMBER(TO_CHAR(DATEADD(DAY , SEQ4(), '2019-01-01'), 'YYYYMMDD')) AS DATE_KEY,
     DATEADD(DAY ,SEQ4(), '2019-01-01') AS FULL_DATE,
     YEAR(DATEADD(DAY , SEQ4(), '2019-01-01')) AS YEAR,
     MONTH(DATEADD(DAY, SEQ4(), '2019-01-01')) AS MONTH,
     MONTHNAME(DATEADD(DAY , SEQ4(), '2019-01-01')) AS MONTH_NAME,
     DAY(DATEADD(DAY,SEQ4(),'2019-01-01')) AS DAY,
     DAYNAME(DATEADD(DAY,SEQ4(), '2010-01-01')) AS DAY_NAME,
     'Q' || QUARTER(DATEADD(DAY,SEQ4(),'2019-01-01')) AS QUARTER,

     CASE 
        WHEN DAYOFWEEKISO(DATEADD(DAY,SEQ4(), '2019-01-01')) IN (6,7)
        THEN 'YES'
        ELSE 'NO'
    END AS WEEKEND_FLAG

FROM TABLE (GENERATOR(ROWCOUNT => 217));

SELECT * FROM DIM_DATE 
LIMIT 10;
